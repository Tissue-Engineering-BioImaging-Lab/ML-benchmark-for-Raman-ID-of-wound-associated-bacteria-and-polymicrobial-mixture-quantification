        es = tf.keras.callbacks.EarlyStopping(monitor="val_loss", patience=3, restore_best_weights=True)
        m.fit(Xs[fi].astype(np.float32)[..., None], oh(y[fi]), validation_data=(Xs[vi].astype(np.float32)[..., None], oh(y[vi])),
              epochs=2 if args.quick else 50, batch_size=p["batch_size"], callbacks=[es], verbose=2)
        pn = np.argmax(m.predict(noise(Xs[te], 42).astype(np.float32)[..., None], batch_size=1024, verbose=0), axis=1)
        json.dump({"acc_noisy_after_scaling": float(np.mean(pn == y[te]))}, open(f, "w"))
        log(f"DONE  mixed_{k}_clean_altnoise: {100*np.mean(pn == y[te]):.2f}%")

