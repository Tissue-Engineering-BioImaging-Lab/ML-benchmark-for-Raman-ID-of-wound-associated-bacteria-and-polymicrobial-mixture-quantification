def cochran(M):
    from scipy.stats import chi2
    X = np.asarray(M, float); n, k = X.shape; cs, rs, N = X.sum(0), X.sum(1), X.sum()
    den = k * N - np.sum(rs ** 2)
    if den == 0: return float("nan"), k - 1, float("nan")
    Q = k * (k - 1) * np.sum((cs - N / k) ** 2) / den; return Q, k - 1, chi2.sf(Q, k - 1)

def statistics():
    from statsmodels.stats.contingency_tables import mcnemar
    from statsmodels.stats.multitest import multipletests
    RES = os.path.join(OUT, "results"); os.makedirs(RES, exist_ok=True)
    RATIO = ["1:9", "3:7", "5:5", "7:3", "9:1"]; models = ["rf", "xg", "cnn", "tr"]
    for tag, cond, key in [("clean_clean", "clean", "pred_clean"), ("clean_noisy", "clean", "pred_noisy"), ("retrained_noisy", "retr", "pred_noisy")]:
        C = {}; ids = y = files = None
        for k in models:
            d = np.load(os.path.join(JOBS, f"mixed_{k}_{cond}.npz"), allow_pickle=True)
            if ids is None: ids, y, files = d["test_ids"], d["y"], d["files"]
            check(f"same test spectra for all models ({tag}, {k})", np.array_equal(ids, d["test_ids"]), hard=True)
            C[k] = (d[key] == y).astype(int)
        ftest = files[ids]; M = np.column_stack([C[k] for k in models])
        rows = []
        for c in range(5):
            s = y == c; q = cochran(M[s]); rows.append({"Ratio (Sa:Pa)": RATIO[c], "n": int(s.sum()), "Q": q[0], "df": q[1], "p": q[2]})
        q = cochran(M); rows.append({"Ratio (Sa:Pa)": "All", "n": len(y), "Q": q[0], "df": q[1], "p": q[2]})
        pd.DataFrame(rows).to_csv(os.path.join(RES, f"{tag}_cochran.csv"), index=False)
        rng = np.random.default_rng(42)
        groups = {c: np.unique(ftest[y == c]) for c in np.unique(y)}; byf = {f: np.where(ftest == f)[0] for f in np.unique(ftest)}
        boots = np.array([M[np.concatenate([byf[f] for c in groups for f in rng.choice(groups[c], len(groups[c]), replace=True)])].mean(0) for _ in range(2000)])
        pr, raw = [], []
        for (i, a), (j, b) in itertools.combinations(enumerate(models), 2):
            ca, cb = C[a], C[b]; a1 = int(np.sum((ca == 1) & (cb == 0))); b1 = int(np.sum((ca == 0) & (cb == 1)))
            check(f"McNemar identity ({tag}, {a} vs {b})", b1 - a1 == int(cb.sum() - ca.sum()), hard=True)
            tab = [[int(np.sum((ca == 1) & (cb == 1))), a1], [b1, int(np.sum((ca == 0) & (cb == 0)))]]
            ex = (a1 + b1) < 25; r = mcnemar(tab, exact=ex, correction=not ex); raw.append(r.pvalue)
            lo, hi = np.percentile(boots[:, j] - boots[:, i], [2.5, 97.5])
            pr.append({"Model 1": MNAME[a], "Model 2": MNAME[b], "Model 1 only correct": a1, "Model 2 only correct": b1, "chi2": r.statistic,
                       "p_raw": r.pvalue, "Acc. diff (M2-M1, pp)": 100 * (cb.mean() - ca.mean()),
                       "95% CI replicate-level (pp)": f"{100*lo:.2f} to {100*hi:.2f}", "CI excludes 0": bool(lo > 0 or hi < 0)})
        df = pd.DataFrame(pr); df["p_holm"] = multipletests(raw, method="holm")[1]; df["Significant (Holm)"] = df["p_holm"] < 0.05
        df.to_csv(os.path.join(RES, f"{tag}_mcnemar.csv"), index=False); log(f"statistics written: {tag}")

def summarise():
    from sklearn.metrics import precision_recall_fscore_support
    RES = os.path.join(OUT, "results"); os.makedirs(RES, exist_ok=True); rows = []
    for task in ("single", "mixed"):
        for k in ("rf", "xg", "cnn", "tr"):
            for cond in ("clean", "retr"):
                d = np.load(os.path.join(JOBS, f"{task}_{k}_{cond}.npz"), allow_pickle=True); meta = json.load(open(os.path.join(JOBS, f"{task}_{k}_{cond}.json")))
                for key, lab in ([("pred_clean", "clean/clean"), ("pred_noisy", "clean/noisy")] if cond == "clean" else [("pred_noisy", "retrained/noisy"), ("pred_clean", "retrained/clean")]):
                    pr, rc, f1, _ = precision_recall_fscore_support(d["y"], d[key], average="macro", zero_division=0)
                    rows.append(dict(task=task, model=MNAME[k], condition=lab, n_test=len(d["y"]), accuracy=100 * np.mean(d[key] == d["y"]),
                                     precision=pr, recall=rc, f1=f1, train_acc=100 * meta["train_acc"], cv_folds=";".join(f"{v:.4f}" for v in meta["cv"]),
                                     cv_mean=100 * np.mean(meta["cv"]) if meta["cv"] else np.nan, epochs_run=meta.get("epochs_run"), best_epoch=meta.get("best_epoch")))
    pd.DataFrame(rows).to_csv(os.path.join(RES, "accuracy_tables.csv"), index=False)
    seeds = {}
    for k, cond, key in [("cnn", "clean", "pred_clean"), ("tr", "clean", "pred_clean"), ("cnn", "retr", "pred_noisy"), ("tr", "retr", "pred_noisy")]:
        vals = []
        for suf in [""] + [f"_seed{s}" for s in range(1, 6)]:
            f = os.path.join(JOBS, f"single_{k}_{cond}{suf}.npz")
            if os.path.exists(f): d = np.load(f, allow_pickle=True); vals.append(100 * np.mean(d[key] == d["y"]))
        if vals: seeds[f"{k}_{cond}"] = dict(n=len(vals), mean=float(np.mean(vals)), sd=float(np.std(vals, ddof=1)) if len(vals) > 1 else 0.0,
                                             min=float(min(vals)), max=float(max(vals)), n_fail=int(sum(v < 50 for v in vals)), values=[round(v, 2) for v in vals])
    json.dump(seeds, open(os.path.join(RES, "seed_summary.json"), "w"), indent=1)
    alt = {}
    for k in ("cnn", "tr"):
        f = os.path.join(JOBS, f"mixed_{k}_clean_altnoise.json")
        if os.path.exists(f):
            a = json.load(open(f))["acc_noisy_after_scaling"] * 100
            b = json.load(open(os.path.join(JOBS, f"mixed_{k}_clean.json")))["acc_noisy"] * 100
            alt[k] = dict(noise_after_scaling=a, noise_before_scaling=b, diff=a - b)
    if alt: alt["max_abs_diff"] = max(abs(v["diff"]) for v in alt.values()); json.dump(alt, open(os.path.join(RES, "noise_alt.json"), "w"), indent=1)
    log("summary tables written")
    df = pd.DataFrame(rows)
    for task in ("single", "mixed"):
        t = df[df.task == task].pivot_table(index="model", columns="condition", values="accuracy").round(2)
        log(f"\n{task.upper()} accuracy (%):\n{t.to_string()}")

