"""
Raman benchmark - corrected GPU re-run (single command, resumable).

Trains Random Forest, XGBoost, 1D-CNN and 1D-Transformer on the single-species and mixed-ratio
datasets under the corrected protocol, computes training accuracy and 5-fold cross-validation for
every model, runs the statistics, checks everything, and zips the results.

Run through RUN_ME.ps1 (Docker, GPU). Do not edit this file.

Protocol (why each rule exists is in README.md):
  1. Data are read from "Distributable Notebooks/data" with join="inner".
  2. The 80/20 stratified split (seed 42) is made FIRST, on clean spectra.
  3. White noise (0.05 x each spectrum's s.d.) is added AFTER the split, to min-max spectra, before any
     model-specific scaling. Test noise seed 42; training-augmentation noise seed 43. Every model is
     evaluated on the SAME noisy test spectra.
  4. Retraining = training spectra + a noisy copy of them. Never noisy copies of test spectra.
  5. CNN/Transformer: StandardScaler fitted on training rows only. Early-stopping validation rows are held
     out together with their noisy copies.
  6. Cross-validation adds noise inside each fold, after the fold split.
"""
