def cols(n): return list(range(1, n + 1))
def fit_tree(k, X, y, p, args):
    if k == "rf":
        from sklearn.ensemble import RandomForestClassifier
        q = dict(p);  q["n_estimators"] = 20 if args.quick else q["n_estimators"]
        m = RandomForestClassifier(**q, random_state=42, n_jobs=-1)
    else:
        from xgboost import XGBClassifier
        q = dict(p); q["n_estimators"] = 20 if args.quick else q["n_estimators"]
        m = XGBClassifier(**q, random_state=42, eval_metric="mlogloss", tree_method="hist", device=XGB_DEVICE)
    m.fit(pd.DataFrame(X, columns=cols(X.shape[1])), y)
    f = lambda Z: np.asarray(m.predict(pd.DataFrame(Z, columns=cols(Z.shape[1])))).astype(int)
    f.model = m
    return f

_TF = None
def tfmod():
    global _TF
    if _TF is None:
        os.environ["TF_CPP_MIN_LOG_LEVEL"] = "2"
        import tensorflow as tf
        for g in tf.config.list_physical_devices("GPU"):
            try: tf.config.experimental.set_memory_growth(g, True)
            except Exception: pass
        _TF = tf
    return _TF

def build(kind, p, L, C):
    tf = tfmod(); Ly = tf.keras.layers; R = tf.keras.regularizers
    if kind == "cnn":
        seq = [Ly.Input(shape=(L, 1))]
        for b in range(p["n_conv_blocks"]):
            seq += [Ly.Conv1D(p["first_filters"] * 2 ** b, p["kernel_size"], padding="same", kernel_regularizer=R.l2(p["l2_strength"])),
                    Ly.LeakyReLU(negative_slope=p["negative_slope"]), Ly.BatchNormalization(), Ly.MaxPooling1D(2)]
        seq += [Ly.Flatten(), Ly.Dropout(p["dropout"]), Ly.Dense(p["dense_units"], activation="relu", kernel_regularizer=R.l2(p["l2_strength"])),
                Ly.Dense(C, activation="softmax")]
        m = tf.keras.Sequential(seq)
    else:
        class Patch(Ly.Layer):
            def __init__(s, ps, d, l2s, **kw):
                super().__init__(**kw); s.ps, s.d = ps, d; s.proj = Ly.Dense(d, kernel_regularizer=R.l2(l2s))
            def build(s, shp):
                s.n = math.ceil(int(shp[1]) / s.ps); s.pad = s.n * s.ps - int(shp[1]); s.pos = Ly.Embedding(s.n, s.d); super().build(shp)
            def call(s, x):
                if s.pad > 0: x = tf.pad(x, [[0, 0], [0, s.pad], [0, 0]])
                x = tf.reshape(x, (tf.shape(x)[0], s.n, s.ps)); return s.proj(x) + s.pos(tf.range(s.n))
        inp = Ly.Input(shape=(L, 1)); x = Patch(p["patch_size"], p["d_model"], p["l2_strength"])(inp); x = Ly.Dropout(p["dropout"])(x)
        kd = max(p["d_model"] // p["num_heads"], 1)
        for _ in range(p["num_transformer_blocks"]):
            a = Ly.LayerNormalization(epsilon=1e-6)(x); a = Ly.MultiHeadAttention(num_heads=p["num_heads"], key_dim=kd, dropout=p["dropout"])(a, a)
            x = Ly.Add()([x, a]); f = Ly.LayerNormalization(epsilon=1e-6)(x)
            f = Ly.Dense(p["ff_dim"], activation="relu", kernel_regularizer=R.l2(p["l2_strength"]))(f); f = Ly.Dropout(p["dropout"])(f)
            f = Ly.Dense(x.shape[-1], kernel_regularizer=R.l2(p["l2_strength"]))(f); x = Ly.Add()([x, f])
        x = Ly.LayerNormalization(epsilon=1e-6)(x); x = Ly.GlobalAveragePooling1D()(x); x = Ly.Dropout(p["dropout"])(x)
        x = Ly.Dense(p["mlp_units"], activation="relu", kernel_regularizer=R.l2(p["l2_strength"]))(x); x = Ly.Dropout(p["dropout"])(x)
        m = tf.keras.Model(inp, Ly.Dense(C, activation="softmax")(x))
    m.compile(optimizer=tf.keras.optimizers.Adam(p["learning_rate"]), loss="categorical_crossentropy", metrics=["accuracy"])
    return m

def fit_nn(kind, Xfit, yfit, Xval, yval, p, C, seed, args):
    """Scaler is fitted on Xfit only (training rows). Returns predictor on raw spectra + info."""
    tf = tfmod(); from sklearn.preprocessing import StandardScaler
    sc = StandardScaler().fit(Xfit)
    tf.keras.utils.set_random_seed(seed); tf.keras.backend.clear_session()
    m = build(kind, p, Xfit.shape[1], C)
    oh = lambda v: tf.keras.utils.to_categorical(v, C).astype(np.float32)
    prep = lambda Z: sc.transform(Z).astype(np.float32)[..., None]
    es = tf.keras.callbacks.EarlyStopping(monitor="val_loss", patience=3, min_delta=0.0, restore_best_weights=True)
    h = m.fit(prep(Xfit), oh(yfit), validation_data=(prep(Xval), oh(yval)), epochs=2 if args.quick else 50,
              batch_size=p["batch_size"], shuffle=True, callbacks=[es], verbose=2)
    info = {"epochs_run": len(h.history["loss"]), "best_epoch": int(np.argmin(h.history["val_loss"]) + 1)}
    f = lambda Z: np.argmax(m.predict(prep(Z), batch_size=1024, verbose=0), axis=1)
    f.model, f.scaler = m, sc
    return f, info

def augment(X, y, idx, seed=43):
    """Rows idx plus a noisy copy of the same rows (never other rows)."""
    return np.vstack([X[idx], noise(X[idx], seed)]), np.concatenate([y[idx], y[idx]])

def nn_train(kind, cond, X, y, tr_idx, p, C, seed, args):
    """Hold out the last 20% of the (already shuffled) training rows for early stopping, with their noisy twins."""
    nval = int(round(0.2 * len(tr_idx))); fit_idx, val_idx = tr_idx[:-nval], tr_idx[-nval:]
    if cond == "clean":
        return fit_nn(kind, X[fit_idx], y[fit_idx], X[val_idx], y[val_idx], p, C, seed, args)
    Xf, yf = augment(X, y, fit_idx); Xv, yv = augment(X, y, val_idx)
    return fit_nn(kind, Xf, yf, Xv, yv, p, C, seed, args)

# ------------------------------------------------------------------ one job = final model + train acc + 5-fold CV
def run_job(task, k, cond, D, args, seed=42, do_cv=True, suffix=""):
    name = f"{task}_{k}_{cond}{suffix}"; f = os.path.join(JOBS, name + ".npz")
    if os.path.exists(f): log(f"skip {name} (already done)"); return
    t0 = time.time(); log(f"START {name}")
    X, y, files, classes, tr, te, Xte_noisy = D["X"], D["y"], D["files"], D["classes"], D["tr"], D["te"], D["Xte_noisy"]
    C = len(classes); p = HP[task][k][cond]; info = {}
    from sklearn.model_selection import StratifiedKFold
    # ---- final model
    if k in ("rf", "xg"):
        if cond == "clean": Xtr, ytr = X[tr], y[tr]
        else: Xtr, ytr = augment(X, y, tr)
        pred = fit_tree(k, Xtr, ytr, p, args)
    else:
        pred, info = nn_train(k, cond, X, y, tr, p, C, seed, args)
        Xtr, ytr = (X[tr], y[tr]) if cond == "clean" else augment(X, y, tr)
    train_acc = float(np.mean(pred(Xtr) == ytr))
    pc, pn = pred(X[te]), pred(Xte_noisy)
    # ---- 5-fold CV (same fold schemes as the original notebooks; noise added inside folds)
    cv = []
    if do_cv and not args.no_cv:
        if k in ("rf", "xg"):
            folds = StratifiedKFold(n_splits=5).split(X, y)                                   # = cross_val_score(cv=5)
        else:
            folds = StratifiedKFold(n_splits=5, shuffle=True, random_state=42).split(X, y)    # = notebook CV loop
        for fi, (a, b) in enumerate(folds, 1):
            if k in ("rf", "xg"):
                if cond == "clean": fp = fit_tree(k, X[a], y[a], p, args); acc = np.mean(fp(X[b]) == y[b])
                else:
                    Xa, ya = augment(X, y, a); fp = fit_tree(k, Xa, ya, p, args); acc = np.mean(fp(noise(X[b], 42)) == y[b])
            else:
                a = a[np.random.default_rng(42 + fi).permutation(len(a))]
                fp, _ = nn_train(k, cond, X, y, a, p, C, 42 + fi, args)
                acc = np.mean(fp(X[b] if cond == "clean" else noise(X[b], 42)) == y[b])
            cv.append(float(acc)); log(f"  {name} CV fold {fi}/5: {acc:.4f}")
    np.savez(f, test_ids=te, y=y[te], pred_clean=pc, pred_noisy=pn, files=files, classes=np.array(classes))
    meta = dict(task=task, model=k, cond=cond, seed=seed, train_acc=train_acc, cv=cv, acc_clean=float(np.mean(pc == y[te])),
                acc_noisy=float(np.mean(pn == y[te])), minutes=round((time.time() - t0) / 60, 1), **info)
    json.dump(meta, open(os.path.join(JOBS, name + ".json"), "w"), indent=1)
    log(f"DONE  {name}: clean {100*meta['acc_clean']:.2f}%  noisy {100*meta['acc_noisy']:.2f}%  train {100*train_acc:.2f}%  "
        f"CV {np.round(cv, 4).tolist()}  ({meta['minutes']} min)")

