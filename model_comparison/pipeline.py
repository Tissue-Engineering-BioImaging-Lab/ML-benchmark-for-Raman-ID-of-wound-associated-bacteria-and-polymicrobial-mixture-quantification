def load(task):
    path = DATA[task]
    if not os.path.isdir(path):
        check(f"data folder exists ({task})", False, path, hard=True)
    files = []
    for root, dirs, fs in os.walk(path):
        dirs[:] = sorted(d for d in dirs if not d.startswith("."))
        files += [os.path.join(root, f) for f in sorted(fs) if f.endswith(".csv")]
    files = sorted(files)
    dfs = []
    for i, p in enumerate(files):
        d = pd.read_csv(p, header=None)
        if i != 0: d = d.iloc[1:].reset_index(drop=True)
        name = os.path.basename(p)
        tgt = next(v for k, v in MIX_TARGETS.items() if k in name) if task == "mixed" else name[:-4]
        d = d.copy(); d["target"] = tgt; d["__file"] = name
        dfs.append(d)
    df = pd.concat(dfs, ignore_index=True, join="inner").copy()      # join="inner": never NaN-padded columns
    df = df.iloc[1:].reset_index(drop=True)                          # drop the wavenumber header row
    classes = sorted(df["target"].unique())
    y = df["target"].map({c: i for i, c in enumerate(classes)}).to_numpy()
    feat = [c for c in df.columns if c not in ("target", "__file")]
    X = df[feat].to_numpy(dtype=float)
    return X, y, df["__file"].to_numpy(), classes

def noise(X, seed, level=0.05):
    rng = np.random.default_rng(seed); X = np.asarray(X, float)
    s = X.std(axis=1, keepdims=True); s = np.where(s == 0, 1e-8, s)
    return X + rng.normal(0.0, level * s, size=X.shape)

